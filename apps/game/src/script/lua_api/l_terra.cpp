// The world being served, built on first use (server/terra.h). Read from the
// map settings (map_meta.txt), which exist while mods load, before the map
// generator does. Server Lua runs on one thread.
static std::string mapgenName(Server *server)
{
	std::string mg_name;
	server->getEmergeManager()->map_settings_mgr->getMapSetting("mg_name", &mg_name);
	return mg_name;
}

static const World &world(Server *server)
{
	std::unique_ptr<World> &built = server->terra().world;
	if (built)
		return *built;
	const MapSettingsManager *settings = server->getEmergeManager()->map_settings_mgr;
	std::string mg_name = mapgenName(server), code;
	if (mg_name != "terra")
		throw LuaError("core.terra: this world isn't generated by terra (mg_name = " + mg_name + ")");
	if (!settings->getMapSetting("mgterra_code", &code))
		throw LuaError("core.terra: this world has no world code (mgterra_code in map_meta.txt)");
	try {
		built = std::make_unique<World>(WorldCode::decode(code));
	} catch (const CodeError &e) {
		throw LuaError(std::string("core.terra: ") + e.what());
	}
	return *built;
}

// The world's weather, opened on first use from <world>/weather.bin (or
// settled fresh) and stepped to the clock on every call.
static weather::Weather &weatherNow(Server *server)
{
	ServerTerra &t = server->terra();
	const World &w = world(server);
	double now = weather::clock(server->getEnv().getDayCount(), server->getEnv().getTimeOfDayF());
	try {
		if (!t.matter)
			t.matter = std::make_unique<matter::Matter>(matter::Matter::load(porting::path_share + DIR_DELIM "matter"));
		if (!t.weather)
			t.weather = weather::Weather::open({ w, *t.matter, server->getWorldPath() + DIR_DELIM "weather.bin" }, now);
		t.weather->advance(now);
	} catch (const std::runtime_error &e) { // matter::MatterError, fluid::FluidError
		throw LuaError(std::string("core.terra.weather: ") + e.what());
	}
	return *t.weather;
}

static double toDouble(fix v)
{
	return (double)v / ONE;
}

static double toDegrees(fix radians)
{
	return toDouble(radians) * 180.0 / M_PI;
}

// Into the table on top of the stack, at full precision (setfloatfield
// narrows to float).
static void setNumber(lua_State *L, const char *key, double value)
{
	lua_pushnumber(L, value);
	lua_setfield(L, -2, key);
}

// Where the engine's clock is in the year.
static fix hourNow(Server *server)
{
	return (fix)(server->getEnv().getTimeOfDayF() * ONE);
}

static Calendar today(Server *server, const World &w)
{
	return calendar(w.code().year, server->getEnv().getDayCount(), hourNow(server));
}

// The world model's column for a position (nodes): its block, z held inside
// the world (beyond the polar edge the sky and climate are the edge's); on a
// planet, the column at its latitude and longitude, wherever it stands (in
// the core too). None for a node that stores no cell (seam): no place.
static std::optional<std::array<int32_t, 2>> placeColumn(Server *server, const World &w, const v3f &pos)
{
	if (const planet::Atlas *atlas = server->atlas()) {
		const std::optional<terragen::Atlas::Vec> p =
				atlas->point(planet::Atlas::moverNode(pos.X, pos.Y, pos.Z), pos.X, pos.Y, pos.Z);
		if (!p)
			return std::nullopt;
		const std::array<int32_t, 2> c = terra::equirect(std::atan2(p->y, std::hypot(p->x, p->z)),
				std::atan2(p->z, p->x), w.code().size);
		return std::array<int32_t, 2>{ c[0], c[1] };
	}
	int32_t half = w.code().size / 2;
	return std::array<int32_t, 2>{ (int32_t)std::floor(pos.X + 0.5f),
		std::clamp<int32_t>((int32_t)std::floor(pos.Z + 0.5f), 1 - half, half) };
}

// The same where there must be one (a player, a sky): seam is an error.
static std::array<int32_t, 2> worldColumn(Server *server, const World &w, const v3f &pos)
{
	if (const std::optional<std::array<int32_t, 2>> c = placeColumn(server, w, pos))
		return *c;
	throw LuaError("core.terra: the position is seam: on no column of the planet");
}

// core.terra.enabled() → whether terra generated this world (the Lab, for
// one, isn't); every other call raises where this is false.
int ModApiTerra::l_enabled(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	lua_pushboolean(L, mapgenName(getServer(L)) == "terra");
	return 1;
}

// core.terra.world() → { code, size, tilt, year_days, star, space, boundary }:
// space is the z north of which the map is empty (World::spaceFrom);
// boundary, the height above the sea where space begins (terragen::Map::BOUNDARY)
int ModApiTerra::l_world(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	const WorldCode &c = world(getServer(L)).code();
	lua_createtable(L, 0, 8);
	setstringfield(L, -1, "code", c.text);
	setintfield(L, -1, "space", world(getServer(L)).spaceFrom());
	setNumber(L, "boundary", terragen::Map::BOUNDARY);
	setintfield(L, -1, "size", c.size);
	setNumber(L, "tilt", toDouble(c.tilt));
	setintfield(L, -1, "year_days", c.year);
	setstringfield(L, -1, "star", c.star->id);
	return 1;
}

// core.terra.calendar() → { year, day, date, year_days }: year and day count
// from 1; date runs 0..1 through the year (0 = northern spring equinox).
int ModApiTerra::l_calendar(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	const World &w = world(getServer(L));
	Calendar c = today(getServer(L), w);
	lua_createtable(L, 0, 4);
	setintfield(L, -1, "year", c.year + 1);
	setintfield(L, -1, "day", c.day + 1);
	setNumber(L, "date", toDouble(c.date));
	setintfield(L, -1, "year_days", w.code().year);
	return 1;
}

// core.terra.sun(pos) → { latitude, declination, elevation (degrees),
// daylight (share of the day the sun is up), season }
int ModApiTerra::l_sun(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	const World &w = world(getServer(L));
	v3f pos = check_v3f(L, 1);
	fix latitude = World::latitude(w.v(worldColumn(getServer(L), w, pos)[1]));
	Calendar c = today(getServer(L), w);
	fix decl = declination(w.code().tilt, c.date);
	lua_createtable(L, 0, 5);
	setNumber(L, "latitude", toDegrees(latitude));
	setNumber(L, "declination", toDegrees(decl));
	setNumber(L, "elevation", toDegrees(elevation(latitude, decl, hourNow(getServer(L)))));
	setNumber(L, "daylight", toDouble(dayShare(latitude, decl)));
	setstringfield(L, -1, "season", SEASON_NAMES[(int)season(c.date, latitude)]);
	return 1;
}

// core.terra.climate(pos) → { temperature (°C, now), biome, heat, wet, rain
// (the year's, relative to the median over land), season (1 summer-wet .. −1 winter-wet) }:
// the climate of today's season at that column.
int ModApiTerra::l_climate(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	const World &w = world(getServer(L));
	v3f pos = check_v3f(L, 1);
	const auto [x, z] = worldColumn(getServer(L), w, pos);
	Calendar c = today(getServer(L), w);
	fix v = w.v(z);
	Column column = w.column(w.u(x), v, w.sunlight(v, c.date));
	lua_createtable(L, 0, 6);
	setNumber(L, "temperature", toDouble(w.temperature(x, z, c.date, hourNow(getServer(L)))));
	setstringfield(L, -1, "biome", BIOME_NAMES[(int)column.biome]);
	setNumber(L, "heat", toDouble(column.heat));
	setNumber(L, "wet", toDouble(column.wet));
	setNumber(L, "rain", toDouble(column.rain));
	setNumber(L, "season", toDouble(column.season));
	return 1;
}

// core.terra.geology(pos) → { province, rock, ore, depth, plate, boundary,
// boundary_distance (blocks), volcano = { distance, active } | nil }: the
// ground at a point. `rock` and `ore` are the bedrock's at that depth below
// the surface (under the soil the game lays); above the ground, its surface rock.
int ModApiTerra::l_geology(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	const World &w = world(getServer(L));
	v3f pos = check_v3f(L, 1);
	const auto [x, z] = worldColumn(getServer(L), w, pos);
	const int32_t y = (int32_t)std::floor(pos.Y + 0.5f);
	fix v = w.v(z);
	Ground g = w.ground(x, z, w.sunlight(v, std::nullopt));
	Strata s = w.strata(x, z, g);
	int32_t depth = std::max(0, g.terrain + 1 - y); // the map generator's ground sits one above terragen's (water level 1)
	Rock rock = w.rock(s, depth, x, y, z);
	Ore ore = w.ore(s, rock, depth, x, y, z);
	const Grid &grid = w.grid();
	int32_t cell = w.cell(w.u(x), v);
	static const char *const BOUNDARIES[] = { "none", "convergent", "divergent", "transform" };

	lua_createtable(L, 0, 8);
	setstringfield(L, -1, "province", PROVINCE_NAMES[(int)s.province]);
	setstringfield(L, -1, "rock", ROCK_NAMES[(int)rock]);
	setstringfield(L, -1, "ore", ORE_NAMES[(int)ore]);
	setintfield(L, -1, "depth", depth);
	setintfield(L, -1, "plate", grid.tectonics.plate[cell]);
	setstringfield(L, -1, "boundary", BOUNDARIES[(int)grid.tectonics.boundary[cell]]);
	setintfield(L, -1, "boundary_distance", grid.tectonics.distance[cell] * (w.code().size / GRID));
	// the nearest volcano whose slopes reach here
	int32_t best = INT32_MAX;
	bool active = false;
	for (uint32_t k = grid.volcano_start[cell]; k < grid.volcano_start[cell + 1]; k++) {
		const Volcano &vo = grid.volcanoes[grid.volcano_list[k]];
		int64_t dx = x - vo.x, dz = z - vo.z;
		int32_t d = (int32_t)std::sqrt((double)(dx * dx + dz * dz));
		if (d < best) {
			best = d;
			active = vo.active;
		}
	}
	if (best != INT32_MAX) {
		lua_createtable(L, 0, 2);
		setintfield(L, -1, "distance", best);
		lua_pushboolean(L, active);
		lua_setfield(L, -2, "active");
		lua_setfield(L, -2, "volcano");
	}
	return 1;
}

// core.terra.cover(minp, maxp) → for every column of the area (x inner, z
// outer, from 1): { density, heat, wet, season, elevation, slope, fertility, bank, tree, roll } as parallel
// arrays, plus season (when the rain falls: 1 summer .. −1 winter) and
// fertility (0..1). What can grow and where trees stand; the game picks what grows.
// For map-generation callbacks: one call per chunk.
int ModApiTerra::l_cover(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	const World &w = world(getServer(L));
	v3s16 a = check_v3s16(L, 1), b = check_v3s16(L, 2);
	if (b.X < a.X || b.Z < a.Z || (b.X - a.X + 1) * (b.Z - a.Z + 1) > 160 * 160)
		throw LuaError("core.terra.cover: the area must run min to max, at most 160 × 160 columns");
	const char *const NAMES[] = { "density", "heat", "wet", "season", "elevation", "slope", "fertility", "bank", "tree", "roll" };
	lua_createtable(L, 0, 10);
	int out = lua_gettop(L);
	for (const char *name : NAMES) {
		lua_createtable(L, (b.X - a.X + 1) * (b.Z - a.Z + 1), 0);
		lua_setfield(L, out, name);
	}
	int n = 1;
	int32_t half = w.code().size / 2;
	const planet::Atlas *atlas = getServer(L)->atlas();
	for (int32_t mz = a.Z; mz <= b.Z; mz++) {
		for (int32_t mx = a.X; mx <= b.X; mx++, n++) {
			// the world model's column (on a planet, the storage column's
			// place at its surface layer; seam and the core are no column:
			// nothing grows)
			int32_t x = mx, z = mz;
			bool column = true;
			if (atlas) {
				const std::optional<std::array<double, 2>> at = atlas->place({ mx, 0, mz });
				column = at.has_value();
				if (at) {
					const std::array<int32_t, 2> c = terra::equirect((*at)[0], (*at)[1], w.code().size);
					x = c[0];
					z = c[1];
				}
			}
			const bool beyond = !column || z >= half || z <= -half;
			const fix sun = beyond ? 0 : w.sunlight(w.v(z), std::nullopt);
			Cover c{ 0, 0, 0, false, false, 0 };
			fix heat = 0, wet = 0, season = 0, elevation = 0;
			if (!beyond) {
				Ground g = w.ground(x, z, sun);
				c = w.cover(x, z, g);
				heat = g.column.heat;
				wet = g.column.wet;
				season = g.column.season;
				elevation = g.column.elevation;
			}
			auto put = [&](const char *name) { lua_getfield(L, out, name); };
			put("density"); lua_pushnumber(L, toDouble(c.density)); lua_rawseti(L, -2, n); lua_pop(L, 1);
			put("heat"); lua_pushnumber(L, toDouble(heat)); lua_rawseti(L, -2, n); lua_pop(L, 1);
			put("wet"); lua_pushnumber(L, toDouble(wet)); lua_rawseti(L, -2, n); lua_pop(L, 1);
			put("season"); lua_pushnumber(L, toDouble(season)); lua_rawseti(L, -2, n); lua_pop(L, 1);
			put("fertility"); lua_pushnumber(L, toDouble(c.fertility)); lua_rawseti(L, -2, n); lua_pop(L, 1);
			put("elevation"); lua_pushnumber(L, toDouble(elevation)); lua_rawseti(L, -2, n); lua_pop(L, 1);
			put("slope"); lua_pushnumber(L, toDouble(c.slope)); lua_rawseti(L, -2, n); lua_pop(L, 1);
			put("bank"); lua_pushboolean(L, c.bank); lua_rawseti(L, -2, n); lua_pop(L, 1);
			put("tree"); lua_pushboolean(L, c.tree); lua_rawseti(L, -2, n); lua_pop(L, 1);
			put("roll"); lua_pushinteger(L, c.roll); lua_rawseti(L, -2, n); lua_pop(L, 1);
		}
	}
	return 1;
}

// A {lo, hi} pair from field `name` of the table at `idx`.
static void readRange(lua_State *L, int idx, const char *name, const std::string &species, double out[2])
{
	lua_getfield(L, idx, name);
	if (!lua_istable(L, -1))
		throw LuaError("core.terra.register_species '" + species + "': " + name + " must be { low, high }");
	for (int k = 0; k < 2; k++) {
		lua_rawgeti(L, -1, k + 1);
		if (!lua_isnumber(L, -1))
			throw LuaError("core.terra.register_species '" + species + "': " + name + " must be { low, high }");
		out[k] = lua_tonumber(L, -1);
		lua_pop(L, 1);
	}
	lua_pop(L, 1);
}

static std::string needString(lua_State *L, int idx, const char *name, const std::string &species)
{
	std::string out;
	if (!getstringfield(L, idx, name, out) || out.empty())
		throw LuaError("core.terra.register_species '" + species + "': " + name + " is required");
	return out;
}

// core.terra.register_species(def): a tree species. def = { name, heat = { lo, hi },
// wet = { lo, hi }, season = { lo, hi } (optional), bank, shore, on = { [block] = true, … },
// trunk, leaves, shape = an L-system as core.spawn_tree takes }. The climate is
// core.terra.cover's. In registration order, the first that fits doesn't win:
// core.terra.species picks among all that fit by the column's roll.
int ModApiTerra::l_register_species(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	luaL_checktype(L, 1, LUA_TTABLE);
	terra::SpeciesDef d{};
	d.name = needString(L, 1, "name", "?");
	ServerTerra &t = getServer(L)->terra();
	if (t.resolved)
		throw LuaError("core.terra.register_species: '" + d.name + "' comes after the species were first used (register them as mods load)");
	for (const terra::SpeciesDef &other : t.species)
		if (other.name == d.name)
			throw LuaError("core.terra.register_species: '" + d.name + "' is registered twice");
	readRange(L, 1, "heat", d.name, d.niche.heat);
	readRange(L, 1, "wet", d.name, d.niche.wet);
	lua_getfield(L, 1, "season");
	d.niche.seasonal = !lua_isnil(L, -1);
	lua_pop(L, 1);
	if (d.niche.seasonal)
		readRange(L, 1, "season", d.name, d.niche.season);
	d.niche.bank = getboolfield_default(L, 1, "bank", false);
	d.niche.shore = getboolfield_default(L, 1, "shore", false);
	d.trunk = needString(L, 1, "trunk", d.name);
	d.leaves = needString(L, 1, "leaves", d.name);

	lua_getfield(L, 1, "on");
	if (!lua_istable(L, -1))
		throw LuaError("core.terra.register_species '" + d.name + "': on must be a set of blocks");
	lua_pushnil(L);
	while (lua_next(L, -2)) {
		if (lua_type(L, -2) == LUA_TSTRING && lua_toboolean(L, -1))
			d.on.push_back(lua_tostring(L, -2));
		lua_pop(L, 1);
	}
	lua_pop(L, 1);
	std::sort(d.on.begin(), d.on.end());

	lua_getfield(L, 1, "shape");
	if (!lua_istable(L, -1))
		throw LuaError("core.terra.register_species '" + d.name + "': shape is required");
	int shape = lua_gettop(L);
	terra::Shape &s = d.shape;
	s.axiom = needString(L, shape, "axiom", d.name);
	getstringfield(L, shape, "rules_a", s.rules_a);
	getstringfield(L, shape, "rules_b", s.rules_b);
	getstringfield(L, shape, "rules_c", s.rules_c);
	getstringfield(L, shape, "rules_d", s.rules_d);
	s.trunk_type = "single";
	getstringfield(L, shape, "trunk_type", s.trunk_type);
	s.angle = getintfield_default(L, shape, "angle", 0);
	s.iterations = getintfield_default(L, shape, "iterations", 0);
	s.random_level = getintfield_default(L, shape, "random_level", 0);
	s.thin_branches = getboolfield_default(L, shape, "thin_branches", false);
	lua_pop(L, 1);

	t.species.push_back(std::move(d));
	return 0;
}

// core.terra.species(pos, ground) → the name of the tree species that grows at
// the column of pos on `ground` (a block name), or nil. Ask where
// core.terra.cover says a tree stands.
int ModApiTerra::l_species(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	Server *server = getServer(L);
	const World &w = world(server);
	v3s16 p = check_v3s16(L, 1);
	std::string ground_name = luaL_checkstring(L, 2);
	const NodeDefManager *ndef = server->getNodeDefManager();
	content_t ground = ndef->getId(ground_name);
	if (ground == CONTENT_IGNORE)
		throw LuaError("core.terra.species: no block called '" + ground_name + "'");

	const std::vector<terra::Species> &species = server->terra().resolve(ndef);

	// the world model's column (on a planet, at its latitude and longitude)
	const std::optional<std::array<int32_t, 2>> column = placeColumn(server, w, v3f(p.X, p.Y, p.Z));
	if (!column)
		return 0; // seam: no place, nothing grows
	const auto [x, z] = *column;
	int32_t half = w.code().size / 2;
	if (z >= half || z <= -half)
		return 0; // beyond the polar edge: nothing grows
	Ground g = w.ground(x, z, w.sunlight(w.v(z), std::nullopt));
	const terra::Species *s = terra::choose(species, terra::spotAt(g, w.cover(x, z, g)), ground);
	if (!s)
		return 0;
	lua_pushstring(L, s->name.c_str());
	return 1;
}

// The far view's generator, built from what the server sends its clients.
static const far::Generator &surfaceGenerator(Server *server)
{
	ServerTerra &t = server->terra();
	if (!t.surface) {
		const std::optional<far::Horizon> h = server->horizon();
		if (!h)
			throw LuaError("core.terra: this world wasn't made by terra");
		const planet::Atlas *atlas = server->atlas();
		t.surface = atlas ? std::make_unique<far::Generator>(*h, *atlas) : std::make_unique<far::Generator>(*h);
	}
	return *t.surface;
}

// core.terra.surface(pos) → { ground, top, water, liquid, trunk, canopy }: the
// column at pos as the generator makes it, without generating it. ground is
// the top solid block's y and top its name; water and liquid the surface of
// any water or lava over it; trunk and canopy, if a tree stands there,
// { low, high, name } (its blocks low to high; none on a planet). What the
// far view draws.
int ModApiTerra::l_surface(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	Server *server = getServer(L);
	const far::Generator &g = surfaceGenerator(server);
	v3s16 p = check_v3s16(L, 1);
	far::Cell column;
	if (const planet::Atlas *atlas = server->atlas()) {
		// a storage column of a region is one place on the planet: the
		// column the generator builds there (its y the layer). No trees: they
		// are planted per map chunk, which a place's column isn't.
		if (!atlas->place({ p.X, 0, p.Z }))
			throw LuaError("core.terra.surface: the column is seam: no place on the planet");
		column = g.column(p.X, p.Z);
	} else {
		// one level-0 tile around the column: its trees are grown exactly
		far::TileKey key{ 0, (s32)std::floor(p.X / (double)far::TILE), (s32)std::floor(p.Z / (double)far::TILE) };
		// neighbouring columns share tiles: keep the last few
		std::deque<far::Tile> &tiles = server->terra().tiles;
		auto it = std::find_if(tiles.begin(), tiles.end(), [&](const far::Tile &t) { return t.key == key; });
		if (it == tiles.end()) {
			tiles.push_front(g.build(key));
			if (tiles.size() > 16)
				tiles.pop_back();
			it = tiles.begin();
		}
		column = it->at(p.X - key.x * far::TILE, p.Z - key.z * far::TILE);
	}
	const far::Cell &c = column;
	const NodeDefManager *ndef = server->getNodeDefManager();
	lua_createtable(L, 0, 6);
	setNumber(L, "ground", c.ground);
	lua_pushstring(L, ndef->get(c.top).name.c_str());
	lua_setfield(L, -2, "top");
	if (c.water > c.ground) {
		setNumber(L, "water", c.water);
		lua_pushstring(L, ndef->get(c.liquid).name.c_str());
		lua_setfield(L, -2, "liquid");
	}
	for (auto [name, run] : { std::pair{ "trunk", &c.trunk }, std::pair{ "canopy", &c.canopy } }) {
		if (run->empty())
			continue;
		lua_createtable(L, 0, 3);
		setNumber(L, "low", run->low);
		setNumber(L, "high", run->high);
		lua_pushstring(L, ndef->get(run->node).name.c_str());
		lua_setfield(L, -2, "name");
		lua_setfield(L, -2, name);
	}
	return 1;
}

// core.terra.weather(pos) → { temperature (°C), humidity (0..1), cloud (0..1),
// precipitation (mm/h), snow, wind = { x, z } (m/s, east and north),
// pressure (hPa), ash (0..1), events = { name, … } }: the weather now at a
// point. The world's atmosphere moves on its own (src/fluid); this reads it.
int ModApiTerra::l_weather(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	Server *server = getServer(L);
	weather::Weather &wx = weatherNow(server);
	const World &w = world(server);
	v3f pos = check_v3f(L, 1);
	const auto [x, z] = worldColumn(getServer(L), w, pos);
	const int32_t y = (int32_t)std::floor(pos.Y + 0.5f);
	fluid::Sample s = wx.sample(x, y, z, wx.now());
	lua_createtable(L, 0, 9);
	setNumber(L, "temperature", s.temperature - 273.15);
	setNumber(L, "humidity", s.humidity);
	setNumber(L, "cloud", s.cloud);
	setNumber(L, "precipitation", s.precipitation);
	lua_pushboolean(L, s.snow);
	lua_setfield(L, -2, "snow");
	lua_createtable(L, 0, 2);
	setNumber(L, "x", s.wind_u);
	setNumber(L, "z", s.wind_v);
	lua_setfield(L, -2, "wind");
	setNumber(L, "pressure", s.pressure / 100);
	setNumber(L, "ash", s.ash);
	lua_newtable(L);
	int n = 1;
	for (int e = 0; e < (int)fluid::Event::Count; e++)
		if (s.events & (1u << e)) {
			lua_pushstring(L, fluid::EVENT_NAMES[e]);
			lua_rawseti(L, -2, n++);
		}
	lua_setfield(L, -2, "events");
	return 1;
}

// core.terra.soil_points() → { { sand, silt, clay, organic }, … } (index + 1 =
// the soil block's param2 + 1): the compositions a soil block can hold. Pure:
// works on any world (the game registers its soil from it).
int ModApiTerra::l_soil_points(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	lua_createtable(L, SOIL_POINTS, 0);
	for (int32_t i = 0; i < SOIL_POINTS; i++) {
		Soil s = soilPoint((uint8_t)i);
		lua_createtable(L, 0, 4);
		setNumber(L, "sand", toDouble(s.sand));
		setNumber(L, "silt", toDouble(s.silt));
		setNumber(L, "clay", toDouble(s.clay));
		setNumber(L, "organic", toDouble(s.organic));
		lua_rawseti(L, -2, i + 1);
	}
	return 1;
}

// core.terra.land(minp, maxp) → for every node of the area (as VoxelArea
// indexes it: x inner, then y, then z, from 1) the name of the block the
// generator places there on an atlas planet (terra::AtlasLand: what the far
// view draws), or false where it stores no cell (seam). Before the game's
// own planting. At most 2²⁴ nodes; raises on another world.
int ModApiTerra::l_land(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	Server *server = getServer(L);
	if (!server->atlas())
		throw LuaError("core.terra.land: this world isn't an atlas planet");
	const v3s16 a = check_v3s16(L, 1), b = check_v3s16(L, 2);
	if (b.X < a.X || b.Y < a.Y || b.Z < a.Z)
		throw LuaError("core.terra.land: the area must run min to max");
	const s64 sx = b.X - a.X + 1, sy = b.Y - a.Y + 1, sz = b.Z - a.Z + 1;
	if (sx * sy * sz > (1 << 24))
		throw LuaError("core.terra.land: at most 2^24 nodes at once");
	const NodeDefManager *ndef = server->getNodeDefManager();
	terra::AtlasLand::Reader reader(surfaceGenerator(server).land());
	lua_createtable(L, (int)(sx * sy * sz), 0);
	// column by column, bottom up: the reader keeps a column while it lasts
	for (s16 z = a.Z; z <= b.Z; z++)
		for (s16 x = a.X; x <= b.X; x++)
			for (s16 y = a.Y; y <= b.Y; y++) {
				const std::optional<MapNode> n = reader.node({ x, y, z });
				if (n)
					lua_pushstring(L, ndef->get(*n).name.c_str());
				else
					lua_pushboolean(L, false);
				lua_rawseti(L, -2, (int)((z - a.Z) * sy * sx + (y - a.Y) * sx + (x - a.X) + 1));
			}
	return 1;
}

// core.terra.world_column(pos) → { x, z }: the world model's column a
// position is (on a planet, the one at its latitude and longitude).
int ModApiTerra::l_world_column(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	const World &w = world(getServer(L));
	const std::array<int32_t, 2> c = worldColumn(getServer(L), w, check_v3f(L, 1));
	lua_createtable(L, 0, 2);
	setintfield(L, -1, "x", c[0]);
	setintfield(L, -1, "z", c[1]);
	return 1;
}

void ModApiTerra::Initialize(lua_State *L, int top)
{
	lua_newtable(L);
	int terra = lua_gettop(L);
	luaL_Reg functions[] = {
		{ "enabled", l_enabled },
		{ "world", l_world },
		{ "calendar", l_calendar },
		{ "sun", l_sun },
		{ "climate", l_climate },
		{ "geology", l_geology },
		{ "cover", l_cover },
		{ "register_species", l_register_species },
		{ "species", l_species },
		{ "surface", l_surface },
		{ "weather", l_weather },
		{ "soil_points", l_soil_points },
		{ "world_column", l_world_column },
		{ "land", l_land },
	};
	for (const luaL_Reg &f : functions) {
		lua_pushcfunction(L, f.func);
		lua_setfield(L, terra, f.name);
	}
	lua_setfield(L, top, "terra");
}
